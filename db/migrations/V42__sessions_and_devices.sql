-- Multi-session support: every refresh token belongs to a session (one sign-in on one device)
-- and is bound to a device id from the server-issued device cookie.
ALTER TABLE identity."RefreshTokens" ADD COLUMN IF NOT EXISTS "SessionId" text;
ALTER TABLE identity."RefreshTokens" ADD COLUMN IF NOT EXISTS "SessionStartedUtc" timestamp with time zone;
ALTER TABLE identity."RefreshTokens" ADD COLUMN IF NOT EXISTS "DeviceId" text;
ALTER TABLE identity."RefreshTokens" ADD COLUMN IF NOT EXISTS "UserAgent" text;

-- Existing tokens join the user's current session, so access tokens issued before this deploy
-- (which carry that session id) keep working.
UPDATE identity."RefreshTokens" rt
SET "SessionId" = COALESCE(u."CurrentSessionId", gen_random_uuid()::text),
    "SessionStartedUtc" = COALESCE(u."LastLoginTime", rt."CreatedUtc"),
    "UserAgent" = u."LastKnownUserAgent"
FROM identity."Users" u
WHERE u."Id" = rt."UserId" AND rt."SessionId" IS NULL;

CREATE INDEX IF NOT EXISTS "IX_RefreshTokens_UserId_SessionId" ON identity."RefreshTokens" ("UserId", "SessionId");

-- Devices the user has signed in from. Used to spot a new device (email alert / optional code).
CREATE TABLE IF NOT EXISTS identity."UserDevices" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "UserId" text NOT NULL,
    "DeviceId" text NOT NULL,
    "FirstSeenUtc" timestamp with time zone NOT NULL,
    "LastSeenUtc" timestamp with time zone NOT NULL,
    "LastIp" text,
    "UserAgent" text,
    CONSTRAINT "PK_UserDevices" PRIMARY KEY ("UserId", "Id"),
    CONSTRAINT "FK_UserDevices_Users_UserId" FOREIGN KEY ("UserId") REFERENCES identity."Users" ("Id") ON DELETE CASCADE
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_UserDevices_UserId_DeviceId" ON identity."UserDevices" ("UserId", "DeviceId");

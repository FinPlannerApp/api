-- V43: Release notes live in the database and are written by Flyway migrations.
--
-- One row per release of the app ("app" = the UI) or the backend ("server"), with short notes
-- (ReleaseNoteItems) for the "What's new" window. Minor and major releases also point at a blog
-- article (BlogSlug -> BlogPosts); patch releases have no article of their own and are listed under
-- the next minor/major article automatically.
--
-- To add a release, create db/migrations/V<next>__release_notes_<stream>_<version>.sql (see V44 for the pattern).

CREATE TABLE IF NOT EXISTS accounts."ReleaseNotes" (
    "Id"         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Stream"     VARCHAR(10)  NOT NULL CHECK ("Stream" IN ('app', 'server')),
    "Version"    VARCHAR(20)  NOT NULL,
    "ReleasedOn" DATE         NOT NULL,
    "Summary"    TEXT         NULL,
    "BlogSlug"   VARCHAR(255) NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_ReleaseNotes_Stream_Version" ON accounts."ReleaseNotes" ("Stream", "Version");

CREATE TABLE IF NOT EXISTS accounts."ReleaseNoteItems" (
    "Id"             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ReleaseNoteId"  INT         NOT NULL REFERENCES accounts."ReleaseNotes" ("Id") ON DELETE CASCADE,
    "SortOrder"      INT         NOT NULL,
    "Type"           VARCHAR(10) NOT NULL CHECK ("Type" IN ('new', 'improved', 'fixed')),
    "Text"           TEXT        NOT NULL
);

CREATE INDEX IF NOT EXISTS "IX_ReleaseNoteItems_ReleaseNoteId" ON accounts."ReleaseNoteItems" ("ReleaseNoteId", "SortOrder");
